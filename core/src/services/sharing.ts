/** SMB/NFS/FTP shares, local users/groups, ACLs and Samba config generation. */
import fs from 'node:fs';
import { config } from '../config.ts';
import { all, get, insert, remove, update } from '../db.ts';
import { logger } from '../logger.ts';
import {
  ApiError, asObject, id, optionalBoolean, optionalString, requireOneOf, requireString, stringArray,
} from '../util.ts';

export interface Share {
  id: string;
  name: string;
  path: string;
  disk: string;
  protocol: 'smb' | 'nfs' | 'ftp';
  users: string[];
  groups: string[];
  permissions: string;
  recycle: boolean;
  readOnly: boolean;
  acl: Array<Record<string, unknown>>;
  createdAt?: number;
}

export function listShares(): Share[] {
  return all<Share>('shares');
}

export function getShare(shareId: string): Share {
  const share = get<Share>('shares', shareId);
  if (!share) throw new ApiError('NOT_FOUND', 'Share not found', 404);
  return share;
}

/** Render an include file suitable for smb.conf's `include =` directive. */
export function generateSambaConfig(shares: Share[]): string {
  const lines: string[] = ['# Generated by WrexrOS - do not edit by hand', ''];
  for (const share of shares) {
    if (share.protocol !== 'smb') continue;
    const safePath = share.path.replace(/["\r\n]/g, '');
    lines.push(`[${share.name}]`);
    lines.push(`   path = ${safePath}`);
    lines.push(`   comment = WrexrOS share ${share.name}`);
    lines.push(`   read only = ${share.readOnly ? 'yes' : 'no'}`);
    lines.push('   printable = no');
    lines.push(`   create mask = ${share.permissions || '0775'}`);
    if (share.users.length) lines.push(`   valid users = ${share.users.join(' ')}`);
    if (share.groups.length) lines.push(`   force group = ${share.groups[0]}`);
    if (share.recycle) lines.push('   vfs objects = recycle', '   recycle:repository = .recycle/%U');
    lines.push('');
  }
  return lines.join('\n');
}

/** Only ever writes the generated config on Linux, outside demo mode. */
export function syncSambaConfig(shares: Share[] = listShares()): void {
  if (config.demoMode || process.platform !== 'linux') return;
  try {
    fs.writeFileSync('/etc/samba/wrexr-shares.conf', generateSambaConfig(shares), 'utf8');
  } catch (error) {
    logger.warn('Could not update Samba config', { error: String(error) });
  }
}

export function createShare(input: Record<string, unknown>): Share {
  const body = asObject(input);
  const name = requireString(body, 'name', { pattern: /^[A-Za-z0-9_.-]{1,64}$/ });
  if (listShares().some((share) => share.name === name)) {
    throw new ApiError('CONFLICT', 'A share with that name already exists', 409);
  }
  const share = insert<Share>('shares', {
    name,
    path: requireString(body, 'path', { max: 4096 }),
    disk: optionalString(body, 'disk'),
    protocol: requireOneOf(body, 'protocol', ['smb', 'nfs', 'ftp'] as const, 'smb'),
    users: stringArray(body.users, 'users'),
    groups: stringArray(body.groups, 'groups'),
    permissions: optionalString(body, 'permissions', '0775'),
    recycle: optionalBoolean(body, 'recycle', true),
    readOnly: optionalBoolean(body, 'readOnly', false),
    acl: Array.isArray(body.acl) ? (body.acl as Array<Record<string, unknown>>) : [],
    createdAt: Date.now(),
  });
  for (const user of share.users) {
    insert('users_shares', { user, share: share.id, permission: share.readOnly ? 'r' : 'rw' });
  }
  syncSambaConfig();
  return share;
}

export function updateShare(shareId: string, input: Record<string, unknown>): Share {
  getShare(shareId);
  const body = asObject(input);
  const patch: Partial<Share> = {};
  if (body.name !== undefined) patch.name = requireString(body, 'name', { pattern: /^[A-Za-z0-9_.-]{1,64}$/ });
  if (body.path !== undefined) patch.path = requireString(body, 'path', { max: 4096 });
  if (body.disk !== undefined) patch.disk = optionalString(body, 'disk');
  if (body.protocol !== undefined) patch.protocol = requireOneOf(body, 'protocol', ['smb', 'nfs', 'ftp'] as const);
  if (body.users !== undefined) patch.users = stringArray(body.users, 'users');
  if (body.groups !== undefined) patch.groups = stringArray(body.groups, 'groups');
  if (body.permissions !== undefined) patch.permissions = optionalString(body, 'permissions', '0775');
  if (body.recycle !== undefined) patch.recycle = optionalBoolean(body, 'recycle');
  if (body.readOnly !== undefined) patch.readOnly = optionalBoolean(body, 'readOnly');
  const share = update<Share>('shares', shareId, patch) as Share;
  syncSambaConfig();
  return share;
}

export function deleteShare(shareId: string): { deleted: boolean } {
  getShare(shareId);
  for (const join of all<Record<string, unknown>>('users_shares').filter((item) => item.share === shareId)) {
    remove('users_shares', String(join.id));
  }
  const deleted = remove('shares', shareId);
  syncSambaConfig();
  return { deleted };
}

export interface LocalUser {
  id: string;
  username: string;
  groups: string[];
  shell: string;
}

export function listLocalUsers(): LocalUser[] {
  return all<LocalUser>('local_users');
}

export function createLocalUser(input: Record<string, unknown>): LocalUser {
  const body = asObject(input);
  const username = requireString(body, 'username', { pattern: /^[A-Za-z0-9_.-]{1,64}$/ });
  if (listLocalUsers().some((user) => user.username === username)) {
    throw new ApiError('CONFLICT', 'User already exists', 409);
  }
  return insert<LocalUser>('local_users', {
    username,
    groups: stringArray(body.groups, 'groups'),
    shell: optionalString(body, 'shell', '/usr/sbin/nologin'),
  });
}

export function deleteLocalUser(userId: string): { deleted: boolean } {
  return { deleted: remove('local_users', userId) };
}

export interface Group {
  id: string;
  name: string;
  members: string[];
}

export function listGroups(): Group[] {
  return all<Group>('groups');
}

export function createGroup(input: Record<string, unknown>): Group {
  const body = asObject(input);
  const name = requireString(body, 'name', { pattern: /^[A-Za-z0-9_.-]{1,64}$/ });
  if (listGroups().some((group) => group.name === name)) {
    throw new ApiError('CONFLICT', 'Group already exists', 409);
  }
  return insert<Group>('groups', { name, members: stringArray(body.members, 'members') });
}

export function updateAcl(
  shareId: string,
  input: Record<string, unknown> | Array<Record<string, unknown>>,
): Array<Record<string, unknown>> {
  const share = getShare(shareId);
  const body = Array.isArray(input) ? { acl: input } : asObject(input);
  const entries = Array.isArray(body.acl) ? (body.acl as Array<Record<string, unknown>>) : [];
  const acl = entries.map((entry) => ({
    id: typeof entry.id === 'string' ? entry.id : id(),
    principal: requireString(entry, 'principal'),
    type: entry.type === 'group' ? 'group' : 'user',
    permission: entry.permission === 'r' || entry.permission === 'rw' ? entry.permission : 'r',
  }));
  for (const existing of all<Record<string, unknown>>('acls').filter((item) => item.share === shareId)) {
    remove('acls', String(existing.id));
  }
  for (const entry of acl) {
    insert('acls', { share: shareId, ...entry });
  }
  update<Share>('shares', shareId, { acl });
  syncSambaConfig([{ ...share, acl }]);
  return acl;
}
